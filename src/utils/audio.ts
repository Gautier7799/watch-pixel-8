// Web Audio API Sound & Haptics Engine for Pixel Watch Studio

let audioCtx: AudioContext | null = null;

function unlockAudioContext() {
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === 'suspended') {
    audioCtx.resume().catch(() => {});
  }
}

// Global user interaction listener for mobile audio unlock
if (typeof window !== 'undefined') {
  const events = ['touchstart', 'touchend', 'mousedown', 'keydown'];
  const unlocker = () => {
    unlockAudioContext();
    events.forEach((evt) => window.removeEventListener(evt, unlocker));
  };
  events.forEach((evt) => window.addEventListener(evt, unlocker, { passive: true }));
}

function getAudioContext(): AudioContext | null {
  if (typeof window === 'undefined') return null;
  unlockAudioContext();
  return audioCtx;
}

export function playCrownTickSound() {
  try {
    const ctx = getAudioContext();
    if (!ctx) return;
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(1400, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(400, ctx.currentTime + 0.025);

    gain.gain.setValueAtTime(0.08, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.025);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start();
    osc.stop(ctx.currentTime + 0.025);
  } catch {
    // Graceful fallback
  }
}

